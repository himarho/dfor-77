      SUBROUTINE D7ZRFL(KEY, VAL, VLEN, STATUS)
      LOGICAL D7ZIOK
      CHARACTER*(*) KEY, VAL
      INTEGER VLEN, STATUS, XLEN
      CHARACTER*65536 LINE, TOKEN
      CHARACTER*32 MARK, ENC
      INTEGER FOUND, S, E
      LOGICAL D7ZKOK, D7ZFAD, D7ZRFK, OK
      STATUS = 0
      KEY = ' '
      VAL = ' '
      VLEN = 0
      READ(5,'(A)',END=900,ERR=900) LINE
      IF (.NOT. D7ZFAD(LINE)) GOTO 900
      CALL D7ZTQR(LINE, 1, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(MARK)) GOTO 900
      MARK = LINE(S:E)
      CALL D7ZTQR(LINE, 2, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(KEY)) GOTO 900
      IF (.NOT. D7ZKOK(LINE(S:E), E - S + 1)) GOTO 900
      KEY = LINE(S:E)
      CALL D7ZTQR(LINE, 3, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(ENC)) GOTO 900
      ENC = LINE(S:E)
      IF (ENC .NE. 'pct' .AND. ENC .NE. 'raw') GOTO 900
      CALL D7ZTQR(LINE, 4, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (MARK .NE. 'K') GOTO 900
      IF (.NOT. D7ZIOK(LINE(S:E), E - S + 1, XLEN)) GOTO 900
      IF (XLEN .LT. 0) GOTO 900
      IF (XLEN .GT. LEN(VAL)) GOTO 900
      CALL D7ZTQR(LINE, 5, S, E, FOUND)
      IF (XLEN .EQ. 0) THEN
         IF (FOUND .NE. 0) GOTO 900
         IF (.NOT. D7ZRFK(KEY)) GOTO 900
         RETURN
      ENDIF
      IF (FOUND .EQ. 0) GOTO 900
      IF (XLEN .NE. E - S + 1) GOTO 900
      CALL D7ZTQR(LINE, 6, S, E, FOUND)
      IF (FOUND .NE. 0) GOTO 900
      TOKEN = LINE(S:E)
      IF (ENC .EQ. 'pct') THEN
         CALL D7ZPDC(TOKEN, XLEN, VAL, VLEN, STATUS)
         IF (STATUS .NE. 0) GOTO 900
      ELSEIF (ENC .EQ. 'raw') THEN
         VAL = TOKEN(1:XLEN)
         VLEN = XLEN
      ELSE
         GOTO 900
      ENDIF
      CALL D7ZUOK(VAL, VLEN, OK)
      IF (.NOT. OK) GOTO 900
      IF (.NOT. D7ZRFK(KEY)) GOTO 900
      RETURN
  900 STATUS = 60
      VLEN = 0
      RETURN
      END

      LOGICAL FUNCTION D7ZRFK(KEY)
      CHARACTER*(*) KEY
      CHARACTER*32 RKEY(64)
      INTEGER RN, I, D7ZLEN
      COMMON /D7RKS/ RN
      COMMON /D7RKY/ RKEY
      LOGICAL D7ZKOK
      D7ZRFK = .FALSE.
      IF (RN .EQ. -1) THEN
         D7ZRFK = .TRUE.
         RETURN
      ENDIF
