      NEG = VAL(1:1) .EQ. '-'
      IF (NEG .OR. VAL(1:1) .EQ. '+') I = 2
      IF (I .GT. VLEN) RETURN
      LIMIT = -2147483647
      IF (NEG) LIMIT = LIMIT - 1
   10 IF (I .GT. VLEN) GOTO 20
