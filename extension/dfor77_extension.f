      SUBROUTINE D7XF64(MIME, MLEN, FPATH, FLEN,
     1                  URI, ULEN, OUTL, TRUN, STAT)
      CHARACTER*(*) MIME, FPATH, URI
      INTEGER MLEN, FLEN, ULEN, OUTL, TRUN, STAT
      INTEGER UNIT, POS, BUF(3), N, C, IOS, I
      CHARACTER*60000 TMP
      CHARACTER*1 CH
      LOGICAL D7ZLOK, D7ZBOK, D7ZMTY, USED
      OUTL = 0
      TRUN = 0
      STAT = 0
      IF (.NOT. D7ZMTY(MIME, MLEN)) GOTO 900
      IF (.NOT. D7ZLOK(FPATH, FLEN, .TRUE.)) GOTO 900
      IF (.NOT. D7ZBOK(URI, ULEN)) GOTO 900
      DO 5 I = 1, FLEN
         IF (ICHAR(FPATH(I:I)) .EQ. 0) GOTO 900
    5 CONTINUE
      DO 6 UNIT = 10, 99
         USED = .TRUE.
         INQUIRE(UNIT=UNIT, OPENED=USED, IOSTAT=IOS)
         IF (IOS .EQ. 0 .AND. .NOT. USED) GOTO 7
    6 CONTINUE
      GOTO 900
    7 TMP = ' '
      POS = 0
      OPEN(UNIT=UNIT, FILE=FPATH(1:FLEN), STATUS='OLD',
     1     ACCESS='STREAM', FORM='UNFORMATTED',
     2     ACTION='READ', ERR=900)
   10 N = 0
   20 READ(UNIT, END=30, ERR=910) CH
      C = ICHAR(CH)
      IF (C .LT. 0) C = C + 256
      N = N + 1
      BUF(N) = C
      IF (N .LT. 3) GOTO 20
   30 IF (N .GT. 0) THEN
         CALL D7ZB64(BUF, N, TMP, POS, STAT)
         IF (STAT .NE. 0) GOTO 910
      ENDIF
      IF (N .EQ. 3) GOTO 10
      CLOSE(UNIT, IOSTAT=IOS)
      IF (IOS .NE. 0) GOTO 900
      CALL D7URI(MIME, MLEN, TMP, POS, URI, ULEN,
     1           OUTL, TRUN, STAT)
      RETURN
  910 CLOSE(UNIT, IOSTAT=IOS)
  900 STAT = 30
      OUTL = 0
      TRUN = 0
      RETURN
      END
