      SUBROUTINE D7ZPDC(IN, ILEN, OUT, OLEN, STATUS)
      CHARACTER*(*) IN, OUT
      INTEGER ILEN, OLEN, STATUS, I, HI, LO, C
      OLEN = 0
      STATUS = 0
      OUT = ' '
      IF (ILEN .LT. 0 .OR. ILEN .GT. LEN(IN)) GOTO 900
      I = 1
   10 IF (I .GT. ILEN) RETURN
      IF (IN(I:I) .EQ. '%') THEN
         IF (I .GT. ILEN - 2) GOTO 900
         CALL D7ZHVL(IN(I+1:I+1), HI, STATUS)
         IF (STATUS .NE. 0) GOTO 900
         CALL D7ZHVL(IN(I+2:I+2), LO, STATUS)
         IF (STATUS .NE. 0) GOTO 900
         C = HI * 16 + LO
         IF (OLEN .GE. LEN(OUT)) GOTO 900
         OLEN = OLEN + 1
         OUT(OLEN:OLEN) = CHAR(C)
         I = I + 3
      ELSE
         IF (OLEN .GE. LEN(OUT)) GOTO 900
         OLEN = OLEN + 1
         OUT(OLEN:OLEN) = IN(I:I)
         I = I + 1
      ENDIF
      GOTO 10
  900 STATUS = 60
      OLEN = 0
      RETURN
      END

      SUBROUTINE D7ZHEX(N, CH)
      INTEGER N
      CHARACTER*1 CH
      IF (N .LT. 10) THEN
         CH = CHAR(ICHAR('0') + N)
      ELSE
         CH = CHAR(ICHAR('A') + N - 10)
      ENDIF
      RETURN
      END

      SUBROUTINE D7ZHVL(CH, N, STATUS)
      CHARACTER*1 CH
      INTEGER N, STATUS, C
      C = ICHAR(CH)
      STATUS = 0
      IF (C .GE. ICHAR('0') .AND. C .LE. ICHAR('9')) THEN
         N = C - ICHAR('0')
      ELSEIF (C .GE. ICHAR('A') .AND. C .LE. ICHAR('F')) THEN
         N = C - ICHAR('A') + 10
      ELSEIF (C .GE. ICHAR('a') .AND. C .LE. ICHAR('f')) THEN
         N = C - ICHAR('a') + 10
      ELSE
         STATUS = 60
         N = 0
      ENDIF
      RETURN
      END

      SUBROUTINE D7ZUOK(VAL, VLEN, OK)
      CHARACTER*(*) VAL
