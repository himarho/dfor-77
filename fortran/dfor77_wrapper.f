      D7ZUCH = -1
      CALL D7ZUOK(VAL, VLEN, OK)
      IF (.NOT. OK) RETURN
      I = 1
      COUNT = 0
      FIRST = 0
      LAST = 0
   10 IF (I .GT. VLEN) GOTO 30
      C = ICHAR(VAL(I:I))
