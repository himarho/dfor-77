      PROGRAM DEMOMD

      INTEGER D7OK,D7EOF,D7DRY,D7MSG
      PARAMETER (D7OK=0,D7EOF=1,D7DRY=20,D7MSG=101)
      CHARACTER*18 WATCH, LOGCH
      PARAMETER (WATCH='100000000000000002')
      PARAMETER (LOGCH='100000000000000006')
      CHARACTER*13 MATCH
      CHARACTER*15 REASON
      CHARACTER*22 NOTICE
      PARAMETER (MATCH='moderate demo',REASON='Demo moderation')
      PARAMETER (NOTICE='Demo moderation result')
      CHARACTER*32 GID, CHID, MID, USER, TEXT
      CHARACTER*64 WHY
      INTEGER STAT, EVNT, BOT, TRUN, TLEN, GLEN, CLEN, MLEN, ULEN
      INTEGER CAN, WLEN, DST, TST

      CALL D7INI(STAT)
      IF (STAT .NE. D7OK) STOP 1

  100 CALL D7NXT(EVNT, STAT)
      IF (STAT .EQ. D7EOF) GOTO 900
      IF (STAT .NE. D7OK) GOTO 100
      IF (EVNT .NE. D7MSG) GOTO 100
      CALL D7BOT(BOT, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (BOT .NE. 0) GOTO 100
      CALL D7CHN(CHID, 32, CLEN, TRUN, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (TRUN .NE. 0) GOTO 100
      IF (CLEN .NE. 18 .OR. CHID .NE. WATCH) GOTO 100
      CALL D7TXT(TEXT, 32, TLEN, TRUN, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (TRUN .NE. 0) GOTO 100
      IF (TLEN .NE. 13 .OR. TEXT .NE. MATCH) GOTO 100
      CALL D7GID(GID, 32, GLEN, TRUN, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (TRUN .NE. 0) GOTO 100
      CALL D7MID(MID, 32, MLEN, TRUN, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (TRUN .NE. 0) GOTO 100
      CALL D7USR(USER, 32, ULEN, TRUN, STAT)
      IF (STAT .NE. D7OK) GOTO 100
      IF (TRUN .NE. 0) GOTO 100

      DST = -1
      CALL D7CDP(CAN, WHY, 64, WLEN, TRUN, STAT)
      IF (STAT .EQ. D7OK .AND. CAN .EQ. 1)
     1   CALL D7DEL(CHID, CLEN, MID, MLEN, REASON, 15, DST)

      TST = -1
      CALL D7CTP(CAN, WHY, 64, WLEN, TRUN, STAT)
      IF (STAT .EQ. D7OK .AND. CAN .EQ. 1)
     1   CALL D7TMO(GID, GLEN, USER, ULEN, 60, REASON, 15, TST)

      IF (DST .EQ. D7OK .OR. DST .EQ. D7DRY .OR.
     1    TST .EQ. D7OK .OR. TST .EQ. D7DRY) THEN
         CALL D7LOG(1, NOTICE, 22, STAT)
         CALL D7SND(LOGCH, 18, NOTICE, 22, STAT)
      ENDIF
      GOTO 100

  900 CALL D7END(STAT)
      STOP
      END
