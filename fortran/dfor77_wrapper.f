      IF (VALUE .LT. (LIMIT + C) / 10) GOTO 900
      VALUE = VALUE * 10 - C
      I = I + 1
      GOTO 10
   20 IF (.NOT. NEG) VALUE = -VALUE
      D7ZIOK = .TRUE.
      RETURN
  900 VALUE = 0
      RETURN
      END

