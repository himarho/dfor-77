         NEED = 1
         C = C - 192
      ENDIF
      DO 20 J = 1, NEED
         CC = ICHAR(VAL(I+J:I+J))
         IF (CC .LT. 0) CC = CC + 256
         C = C * 64 + CC - 128
   20 CONTINUE
      COUNT = COUNT + 1
      IF (TRIM) THEN
         SPACE = (C .GE. 9 .AND. C .LE. 13) .OR. C .EQ. 32
     1      .OR. C .EQ. 133 .OR. C .EQ. 160 .OR. C .EQ. 5760
     2      .OR. (C .GE. 8192 .AND. C .LE. 8202)
     3      .OR. C .EQ. 8232 .OR. C .EQ. 8233 .OR. C .EQ. 8239
     4      .OR. C .EQ. 8287 .OR. C .EQ. 12288
