      SUBROUTINE D7ZRSP(RID, STATUS, FCNT)
      LOGICAL D7ZIOK
      INTEGER RID, STATUS, FCNT
      INTEGER S, E, FOUND
      INTEGER FB, QB, QN, QX, QE, QID, RN
      CHARACTER*65536 LINE
      CHARACTER*32 MAGIC, KIND, TOKEN
      COMMON /D7FRM/ FB
      COMMON /D7RKS/ RN
      COMMON /D7QST/ QB, QN, QX, QE, QID
      LOGICAL D7ZRIO, D7ZFAD
      RN = -1
      STATUS = -1
      FCNT = 0
      IF (RID .EQ. QID .AND. QE .NE. 0) THEN
         STATUS = QE
         RETURN
      ENDIF
      READ(5,'(A)',END=900,ERR=900) LINE
      FB = 0
      IF (.NOT. D7ZFAD(LINE)) GOTO 900
      CALL D7ZTQR(LINE, 1, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(MAGIC)) GOTO 900
      MAGIC = LINE(S:E)
      CALL D7ZTQR(LINE, 2, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(KIND)) GOTO 900
      KIND = LINE(S:E)
      CALL D7ZTQR(LINE, 3, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(TOKEN)) GOTO 900
      TOKEN = LINE(S:E)
      IF (.NOT. D7ZRIO(RID, TOKEN, E - S + 1)) GOTO 900
      CALL D7ZTQR(LINE, 4, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(TOKEN)) GOTO 900
      TOKEN = LINE(S:E)
      IF (.NOT. D7ZIOK(TOKEN, E - S + 1, STATUS)) GOTO 900
      IF (STATUS .LT. 0) GOTO 900
      CALL D7ZTQR(LINE, 5, S, E, FOUND)
      IF (FOUND .EQ. 0) GOTO 900
      IF (E - S + 1 .GT. LEN(TOKEN)) GOTO 900
      TOKEN = LINE(S:E)
      IF (.NOT. D7ZIOK(TOKEN, E - S + 1, FCNT)) GOTO 900
      CALL D7ZTQR(LINE, 6, S, E, FOUND)
      IF (FOUND .NE. 0) GOTO 900
      IF (FCNT .LT. 0) GOTO 900
      IF (FCNT .GT. 64) GOTO 900
      IF (MAGIC .NE. '@D7/1') GOTO 900
      IF (KIND .NE. 'RES') GOTO 900
      RN = 0
      RETURN
  900 STATUS = -1
      FCNT = 0
      RETURN
      END

