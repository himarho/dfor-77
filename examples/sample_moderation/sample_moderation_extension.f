      PROGRAM INCBOT
      INCLUDE 'dfor77.inc'
      INTEGER STAT,EVNT,CLEN,TRUN
      CHARACTER*32 CHID
      CHARACTER*24 TEXT
      TEXT = 'PONG FROM DFOR77 EXT'
      CALL D7INI(STAT)
      IF (STAT .NE. D7OK) STOP 1
  100 CALL D7NXT(EVNT,STAT)
      IF (STAT .EQ. D7TIM) GOTO 100
      IF (STAT .EQ. D7EOF) GOTO 900
      IF (STAT .NE. D7OK) GOTO 100
      IF (EVNT .NE. D7MSG) GOTO 100
      CALL D7CHN(CHID,32,CLEN,TRUN,STAT)
      IF (STAT .NE. D7OK) GOTO 100
      CALL D7SND(CHID,CLEN,TEXT,20,STAT)
      GOTO 100
  900 CALL D7END(STAT)
      STOP
      END
