      SUBROUTINE D7ZCPY(BUF, BUFLEN, VAL, VLEN, OUTLEN, TRUNC, STATUS)
      CHARACTER*(*) BUF, VAL
      INTEGER BUFLEN, VLEN, OUTLEN, TRUNC, STATUS, N
      LOGICAL OK
      OUTLEN = 0
      TRUNC = 0
      IF (VLEN .LT. 0 .OR. VLEN .GT. LEN(VAL)) THEN
         STATUS = 30
         RETURN
      ENDIF
      CALL D7ZUOK(VAL, VLEN, OK)
      IF (.NOT. OK) THEN
         STATUS = 30
         RETURN
      ENDIF
      IF (BUFLEN .LT. 0) THEN
         STATUS = 30
         RETURN
      ENDIF
      IF (BUFLEN .GT. LEN(BUF)) THEN
         STATUS = 30
         OUTLEN = 0
         TRUNC = 0
         RETURN
      ENDIF
      OUTLEN = VLEN
      IF (BUFLEN .EQ. 0) THEN
         IF (VLEN .EQ. 0) THEN
            STATUS = 0
         ELSE
            STATUS = 10
            TRUNC = 1
         ENDIF
         RETURN
      ENDIF
      N = BUFLEN
      IF (N .GT. LEN(BUF)) N = LEN(BUF)
      IF (N .GE. VLEN) THEN
         IF (VLEN .GT. 0) BUF(1:VLEN) = VAL(1:VLEN)
         IF (VLEN .LT. LEN(BUF)) BUF(VLEN+1:) = ' '
         STATUS = 0
      ELSE
   20    IF (N .GT. 0) THEN
            CALL D7ZUOK(VAL, N, OK)
            IF (.NOT. OK) THEN
               N = N - 1
               GOTO 20
            ENDIF
         ENDIF
         IF (N .GT. 0) BUF(1:N) = VAL(1:N)
         IF (N .LT. LEN(BUF)) BUF(N+1:) = ' '
         STATUS = 10
         TRUNC = 1
      ENDIF
      RETURN
      END

