      IF (VLEN .LT. 0 .OR. VLEN .GT. LEN(VAL)) RETURN
      I = 1
   10 IF (I .GT. VLEN) THEN
         OK = .TRUE.
         RETURN
      ENDIF
      C = ICHAR(VAL(I:I))
      IF (C .LT. 0) C = C + 256
      IF (C .LE. 127) THEN
         I = I + 1
         GOTO 10
      ELSEIF (C .GE. 194 .AND. C .LE. 223) THEN
         NEED = 1
      ELSEIF (C .GE. 224 .AND. C .LE. 239) THEN
         NEED = 2
      ELSEIF (C .GE. 240 .AND. C .LE. 244) THEN
         NEED = 3
      ELSE
         RETURN
      ENDIF
      IF (I .GT. VLEN - NEED) RETURN
      CC = ICHAR(VAL(I+1:I+1))
      IF (CC .LT. 0) CC = CC + 256
      IF (C .EQ. 224 .AND. CC .LT. 160) RETURN
      IF (C .EQ. 237 .AND. CC .GT. 159) RETURN
      IF (C .EQ. 240 .AND. CC .LT. 144) RETURN
      IF (C .EQ. 244 .AND. CC .GT. 143) RETURN
      DO 20 J = 1, NEED
         CC = ICHAR(VAL(I+J:I+J))
         IF (CC .LT. 0) CC = CC + 256
         IF (CC .LT. 128 .OR. CC .GT. 191) RETURN
   20 CONTINUE
      I = I + NEED + 1
      GOTO 10
      END
