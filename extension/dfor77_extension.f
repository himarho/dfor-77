      SUBROUTINE D7XQA(QRY, QLEN, CUR, KEY, KLEN, VAL,
     1                  VLEN, OUTL, TRUN, STAT)
      CHARACTER*(*) QRY, KEY, VAL
      INTEGER QLEN, CUR, KLEN, VLEN, OUTL, TRUN, STAT
      INTEGER POS, ELEN, CURV
      CHARACTER*60000 TMP, ENC
      LOGICAL D7ZLOK
      CURV = CUR
      OUTL = 0
      TRUN = 0
      STAT = 0
      IF (.NOT. D7ZLOK(QRY, CURV, .FALSE.)) GOTO 900
      IF (.NOT. D7ZLOK(KEY, KLEN, .TRUE.)) GOTO 900
      IF (.NOT. D7ZLOK(VAL, VLEN, .FALSE.)) GOTO 900
      TMP = ' '
      POS = 0
      IF (CURV .GT. 0) CALL D7ZAPS(TMP, POS, QRY, CURV, STAT)
      IF (CURV .EQ. 0) THEN
         CALL D7ZAPC(TMP, POS, '?', STAT)
      ELSE
         CALL D7ZAPC(TMP, POS, '&', STAT)
      ENDIF
      IF (STAT .NE. 0) GOTO 900
      CALL D7ZPEN(KEY, KLEN, ENC, ELEN, STAT)
      IF (STAT .NE. 0) GOTO 900
      CALL D7ZAPS(TMP, POS, ENC, ELEN, STAT)
      CALL D7ZAPC(TMP, POS, '=', STAT)
      IF (STAT .NE. 0) GOTO 900
      CALL D7ZPEN(VAL, VLEN, ENC, ELEN, STAT)
      IF (STAT .NE. 0) GOTO 900
      CALL D7ZAPS(TMP, POS, ENC, ELEN, STAT)
      IF (STAT .NE. 0) GOTO 900
      CALL D7ZCPY(QRY, QLEN, TMP, POS, OUTL, TRUN, STAT)
      RETURN
